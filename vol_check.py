"""Compute volume from profile using trapezoidal integration of pi*(r_out^2 - r_in^2)*dz."""
import math

PROFILE = [
    ( 0.0, 20.000, 28.443),
    ( 2.0, 20.000, 28.443),
    ( 4.0, 19.998, 28.443),
    ( 6.0, 20.000, 28.443),
    ( 8.0, 20.000, 28.443),
    (10.0, 19.000, 28.443),
    (12.0, 19.070, 27.969),
    (14.0, 19.140, 26.178),
    (16.0, 19.210, 21.603),
    (17.0, 19.244, 21.301),
    (20.0, 19.349, 21.350),
    (25.0, 19.524, 21.525),
    (30.0, 19.698, 21.700),
    (35.0, 19.873, 21.874),
    (40.0, 20.048, 22.049),
    (45.0, 20.222, 22.223),
    (50.0, 20.397, 22.398),
    (51.0, 20.432, 39.058),
    (52.0, 20.524, 38.966),
    (53.0, 20.726, 38.764),
    (54.0, 21.048, 38.442),
    (55.0, 21.503, 37.987),
    (56.0, 22.114, 37.376),
    (57.0, 22.923, 36.566),
    (58.0, 24.015, 35.475),
    (59.0, 25.606, 33.884),
    (59.5, 26.824, 32.666),
    (59.8, 27.975, 31.515),
    (59.9, 28.609, 30.881),
    (59.95, 29.0, 30.5),
]

vol = 0
for i in range(len(PROFILE)-1):
    z1, ri1, ro1 = PROFILE[i]
    z2, ri2, ro2 = PROFILE[i+1]
    dz = z2 - z1
    area1 = math.pi * (ro1**2 - ri1**2)
    area2 = math.pi * (ro2**2 - ri2**2)
    vol += (area1 + area2) / 2 * dz

print(f"Analytical volume: {vol:.1f} mm3")
print(f"Target: 35814 mm3")
print(f"Delta: {abs(vol-35814)/35814*100:.1f}%")
